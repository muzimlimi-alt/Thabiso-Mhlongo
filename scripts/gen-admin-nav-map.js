#!/usr/bin/env node
/* Writes docs-internal/admin-nav-map.md: where every admin page, tab and group lives, read from the real page
   (the sidebar in admin.html) and the registry (js/admin/nav-config.js), so the map cannot drift from the code.
   Run:  node scripts/gen-admin-nav-map.js        (npm test's test/admin-nav.test.js fails if the two disagree) */
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'admin.html'), 'utf8').replace(/\r\n/g, '\n');
const NAV = require(path.join(root, 'js/admin/nav-config.js'));
const strip = (s) => s.replace(/<[^>]+>/g, ' ').replace(/&amp;/g, '&').replace(/&rarr;/g, '->').replace(/\s+/g, ' ').trim();
const roleOf = (a) => a === NAV.ALL ? 'everyone' : a === NAV.OPS ? 'administrator, manager' : 'administrator only';

// sections in page order, each with the tab buttons that sit inside it
const starts = [...html.matchAll(/<div[^>]*\bid="(\w+)"[^>]*class="[^"]*\badmin-section\b|<div[^>]*class="[^"]*\badmin-section\b[^"]*"[^>]*\bid="(\w+)"/g)].map(m => ({ id: m[1] || m[2], at: m.index }));
const tabsOf = {};
starts.forEach((s, i) => {
    const body = html.slice(s.at, i + 1 < starts.length ? starts[i + 1].at : html.length);
    tabsOf[s.id] = [...body.matchAll(/<button[^>]*data-um-tab="(\w+)"[^>]*>([\s\S]*?)<\/button>/g)].map(m => ({ id: m[1], label: strip(m[2]) }));
});

// the sidebar: group titles, flyout parents and links, in order
const sb = html.slice(html.indexOf('class="admin-sidebar'));
const out = [];
let group = null, parent = null;
for (const m of sb.matchAll(/<li class="tm-sidebar-group-title[^>]*><span>([^<]+)<\/span>|<button[^>]*atl-nav-parent[^>]*aria-controls="(\w+)"[\s\S]*?<span class="sh-label[^>]*>([^<]+)<|<ul class="atl-nav-sub[^"]*" id="(\w+)" data-title="([^"]+)"|<a href="#(\w+)" class="tm-nav-link"[^>]*><span class="tm-nav-text">([^<]+)<\/span>|<a href="#(\w+)" class="tm-nav-link sh-nav-item"/g)) {
    if (m[1]) { group = m[1]; parent = null; out.push({ t: 'group', label: group }); }
    else if (m[4]) { parent = m[5]; out.push({ t: 'parent', label: strip(parent) }); }
    else if (m[6]) out.push({ t: 'page', id: m[6], label: strip(m[7]), parent });
    else if (m[8]) { parent = null; out.push({ t: 'page', id: m[8], label: (NAV.sections[m[8]] || {}).label || m[8], parent }); }
}

const L = ['# Admin portal map', '',
    '_Generated by `scripts/gen-admin-nav-map.js` from `admin.html` (sidebar, tabs) and `js/admin/nav-config.js` (names, access). Do not edit by hand; this replaces the old line-number map, `admin-html-map.md`._', '',
    'Reading the tree: **group** (sidebar heading) > page (sidebar link; a flyout parent such as *Bookings* or *Email* just holds several pages) > tabs inside the page. Cards sit inside tabs.', ''];
for (const o of out) {
    if (o.t === 'group') L.push('', `## ${o.label}`, '');
    else if (o.t === 'parent') L.push(`- **${o.label}** (flyout)`);
    else {
        const sec = NAV.sections[o.id] || {};
        const ind = o.parent ? '  ' : '';
        L.push(`${ind}- **${o.label}** — \`#${o.id}\`, ${roleOf(sec.access)}${sec.title && sec.title !== o.label ? `; page heading "${sec.title}"` : ''}`);
        const tabs = tabsOf[o.id] || [];
        if (tabs.length) L.push(`${ind}  - tabs: ${tabs.map(t => `${t.label} (\`${t.id}\`)`).join(' · ')}`);
    }
}
L.push('', '## Retired ids (still work through the alias map)', '');
for (const [from, to] of Object.entries(NAV.aliases)) L.push(`- \`${from}\` -> \`${to}\``);
L.push('', '## Not in the sidebar', '', 'Reached from the account menu or by a link: ' + Object.keys(NAV.sections).filter(id => !out.some(o => o.id === id)).map(id => `\`#${id}\``).join(', ') + '.', '');
fs.writeFileSync(path.join(root, 'docs-internal', 'admin-nav-map.md'), L.join('\n'));
console.log('wrote docs-internal/admin-nav-map.md');
